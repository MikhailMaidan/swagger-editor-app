import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { format, resolveConfig } from "prettier";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const modules = [
  "text-encoding",
  "text-stats",
  "response-assertions",
  "mutation-model",
  "mutation-json",
  "mutation-engine",
].map((name) => `src/lib/${name}.ts`);
const compiled = modules.map((id) => {
  const source = readFileSync(path.join(root, id), "utf8");
  const output = ts.transpileModule(source, {
    compilerOptions: {
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.CommonJS,
      removeComments: false,
    },
  }).outputText;
  const resolved = output.replace(/require\("([^"\n]+)"\)/g, (_, specifier) => {
    const target = specifier.startsWith("@/")
      ? `src/${specifier.slice(2)}.ts`
      : path.posix.normalize(`${path.posix.dirname(id)}/${specifier}.ts`);
    if (!modules.includes(target))
      throw new Error(`Unexpected runtime dependency: ${id} -> ${specifier}`);
    return `require(${JSON.stringify(target)})`;
  });
  return `${JSON.stringify(id)}: function(module, exports, require) {\n${resolved}\n}`;
});
const runtime = `// Generated from the shared assertion and mutation engines. No external dependencies.\nconst mtModules = {\n${compiled.join(",\n")}\n};\nconst mtCache = Object.create(null);\nfunction mtLoad(id) {\n  if (Object.hasOwn(mtCache, id)) return mtCache[id].exports;\n  if (!Object.hasOwn(mtModules, id)) throw new Error("Unknown runtime module");\n  const module = { exports: {} }; mtCache[id] = module;\n  mtModules[id](module, module.exports, mtLoad); return module.exports;\n}\nconst mtEngine = mtLoad("src/lib/mutation-engine.ts");\nconst mtModel = mtLoad("src/lib/mutation-model.ts");\nexport const { runMTProject, materializeMTMutation, mtCheckMatrix, reduceMTChecks, suggestMTAssertion, mtRecordedExpectation, mtReport } = mtEngine;\nexport const { normalizeMTProject, parseMTProject } = mtModel;\n`;
const destination = path.join(root, "src/lib/mutation-runtime-source.ts");
const generated = await format(
  `// Generated by node scripts/build-mutation-runtime.mjs; do not edit by hand.\nexport const MUTATION_RUNTIME_SOURCE = ${JSON.stringify(runtime)};\n`,
  { ...(await resolveConfig(destination)), parser: "typescript" },
);
if (process.argv.includes("--check")) {
  if (
    readFileSync(destination, "utf8").replaceAll("\r\n", "\n") !== generated
  ) {
    process.stderr.write(
      "Mutation runtime is stale. Run node scripts/build-mutation-runtime.mjs.\n",
    );
    process.exitCode = 1;
  }
} else writeFileSync(destination, generated, "utf8");
