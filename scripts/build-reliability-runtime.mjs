import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { format, resolveConfig } from "prettier";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const modules = [
  "text-encoding",
  "reliability-model",
  "reliability-engine",
].map((name) => `src/lib/${name}.ts`);
const compiled = modules.map((id) => {
  const output = ts.transpileModule(readFileSync(path.join(root, id), "utf8"), {
    compilerOptions: {
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.CommonJS,
    },
  }).outputText;
  const resolved = output.replace(/require\("([^"\n]+)"\)/g, (_, specifier) => {
    const target = specifier.startsWith("@/")
      ? `src/${specifier.slice(2)}.ts`
      : path.posix.normalize(`${path.posix.dirname(id)}/${specifier}.ts`);
    if (!modules.includes(target))
      throw new Error(
        `Unexpected reliability runtime dependency: ${specifier}`,
      );
    return `require(${JSON.stringify(target)})`;
  });
  return `${JSON.stringify(id)}: function(module, exports, require) {\n${resolved}\n}`;
});
const runtime = `// Generated from shared reliability source. No external runtime dependencies.\nconst rlModules = {\n${compiled.join(",\n")}\n};\nconst rlCache = Object.create(null);\nfunction rlLoad(id) {\n  if (Object.hasOwn(rlCache, id)) return rlCache[id].exports;\n  if (!Object.hasOwn(rlModules, id)) throw new Error("Unknown reliability runtime module");\n  const module = { exports: {} }; rlCache[id] = module;\n  rlModules[id](module, module.exports, rlLoad); return module.exports;\n}\nconst rlEngine = rlLoad("src/lib/reliability-engine.ts");\nconst rlModel = rlLoad("src/lib/reliability-model.ts");\nexport const { evaluateRLProject, analyzeRLProject, findRLRepairs, recordRLExpectation, rlReport } = rlEngine;\nexport const { normalizeRLProject, parseRLProject } = rlModel;\n`;
const destination = path.join(root, "src/lib/reliability-runtime-source.ts");
const generated = await format(
  `// Generated by node scripts/build-reliability-runtime.mjs; do not edit by hand.\nexport const RELIABILITY_RUNTIME_SOURCE = ${JSON.stringify(runtime)};\n`,
  { ...(await resolveConfig(destination)), parser: "typescript" },
);
if (process.argv.includes("--check")) {
  if (
    readFileSync(destination, "utf8").replaceAll("\r\n", "\n") !==
    generated.replaceAll("\r\n", "\n")
  ) {
    process.stderr.write(
      "Reliability runtime is stale. Run node scripts/build-reliability-runtime.mjs.\n",
    );
    process.exitCode = 1;
  }
} else writeFileSync(destination, generated, "utf8");
