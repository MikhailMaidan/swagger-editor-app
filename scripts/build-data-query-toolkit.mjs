// Build the portable query engine at development time; the app never evaluates source text.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const body = ["data-query-model.ts", "data-query-engine.ts"]
  .map((name) =>
    ts
      .transpileModule(
        fs.readFileSync(path.join(root, "src/lib", name), "utf8"),
        {
          compilerOptions: {
            target: ts.ScriptTarget.ES2022,
            module: ts.ModuleKind.ESNext,
          },
        },
      )
      .outputText.replace(/^import[\s\S]*?;\s*/gm, ""),
  )
  .join("\n");
const runtime =
  "const getByteSize = (text) => new TextEncoder().encode(text).length;\n" +
  body;
const target = path.join(root, "src/lib/data-query-runtime-source.ts");
if (process.argv.includes("--check")) {
  const old = ts.createSourceFile(
    target,
    fs.readFileSync(target, "utf8"),
    ts.ScriptTarget.Latest,
    true,
  );
  const declaration = old.statements
    .filter(ts.isVariableStatement)
    .flatMap((s) => s.declarationList.declarations)
    .find((d) => d.name.getText(old) === "DATA_QUERY_RUNTIME_SOURCE");
  if (
    !declaration?.initializer ||
    !ts.isStringLiteral(declaration.initializer) ||
    declaration.initializer.text !== runtime
  )
    throw new Error(
      "Query toolkit is stale; run node scripts/build-data-query-toolkit.mjs",
    );
} else
  fs.writeFileSync(
    target,
    "// Generated by node scripts/build-data-query-toolkit.mjs. Do not edit by hand.\nexport const DATA_QUERY_RUNTIME_SOURCE = " +
      JSON.stringify(runtime) +
      ";\n",
  );
