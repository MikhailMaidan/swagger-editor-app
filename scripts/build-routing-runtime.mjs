import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { format, resolveConfig } from "prettier";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const modules = ["text-encoding", "routing-model", "routing-engine"].map(
  (name) => `src/lib/${name}.ts`,
);
const compiled = modules.map((id) => {
  const output = ts.transpileModule(readFileSync(path.join(root, id), "utf8"), {
    compilerOptions: {
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.CommonJS,
    },
  }).outputText;
  const resolved = output.replace(/require\("([^"\n]+)"\)/g, (_, specifier) => {
    const target = specifier.startsWith("@/")
      ? `src/${specifier.slice(2)}.ts`
      : path.posix.normalize(`${path.posix.dirname(id)}/${specifier}.ts`);
    if (!modules.includes(target))
      throw new Error(`Unexpected routing runtime dependency: ${specifier}`);
    return `require(${JSON.stringify(target)})`;
  });
  return `${JSON.stringify(id)}: function(module, exports, require) {\n${resolved}\n}`;
});
const runtime = `// Generated from shared routing source. No external runtime dependencies.\nconst rtModules = {\n${compiled.join(",\n")}\n};\nconst rtCache = Object.create(null);\nfunction rtLoad(id) {\n if (Object.hasOwn(rtCache,id)) return rtCache[id].exports;\n if (!Object.hasOwn(rtModules,id)) throw new Error("Unknown routing module");\n const module={exports:{}}; rtCache[id]=module; rtModules[id](module,module.exports,rtLoad); return module.exports;\n}\nconst rtEngine=rtLoad("src/lib/routing-engine.ts");\nconst rtModel=rtLoad("src/lib/routing-model.ts");\nexport const { createRTRouter, runRTProject, compareRTPolicies, recordRTExpectation, rtReport, routingDiagnostics } = rtEngine;\nexport const { normalizeRTProject, normalizeRTConfig, parseRTProject } = rtModel;\n`;
const destination = path.join(root, "src/lib/routing-runtime-source.ts");
const generated = await format(
  `// Generated by node scripts/build-routing-runtime.mjs; do not edit by hand.\nexport const ROUTING_RUNTIME_SOURCE = ${JSON.stringify(runtime)};\n`,
  { ...(await resolveConfig(destination)), parser: "typescript" },
);
if (process.argv.includes("--check")) {
  if (
    readFileSync(destination, "utf8").replaceAll("\r\n", "\n") !==
    generated.replaceAll("\r\n", "\n")
  ) {
    process.stderr.write(
      "Routing runtime is stale. Run node scripts/build-routing-runtime.mjs.\n",
    );
    process.exitCode = 1;
  }
} else writeFileSync(destination, generated, "utf8");
