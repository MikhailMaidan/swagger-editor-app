// Regenerate the portable, dependency-free simulator after model/engine changes.
// The application executes the TypeScript modules directly; no eval is used.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const names = ["saga-model.ts", "saga-engine.ts"];
const body = names
  .map((name) => {
    const source = fs.readFileSync(path.join(root, "src/lib", name), "utf8");
    return ts
      .transpileModule(source, {
        compilerOptions: {
          target: ts.ScriptTarget.ES2022,
          module: ts.ModuleKind.ESNext,
        },
      })
      .outputText.replace(/^import[\s\S]*?;\s*/gm, "");
  })
  .join("\n");
const runtime =
  "const getByteSize = (text) => new TextEncoder().encode(text).length;\n" +
  body;
const output =
  "// Generated by node scripts/build-saga-toolkit.mjs. Do not edit by hand.\nexport const SAGA_RUNTIME_SOURCE = " +
  JSON.stringify(runtime) +
  ";\n";
const target = path.join(root, "src/lib/saga-runtime-source.ts");
if (process.argv.includes("--check")) {
  // Compare semantic string content so repository formatting does not affect this check.
  const old = ts.createSourceFile(
    target,
    fs.readFileSync(target, "utf8"),
    ts.ScriptTarget.Latest,
    true,
  );
  const declaration = old.statements
    .filter(ts.isVariableStatement)
    .flatMap((s) => s.declarationList.declarations)
    .find((d) => d.name.getText(old) === "SAGA_RUNTIME_SOURCE");
  if (
    !declaration?.initializer ||
    !ts.isStringLiteral(declaration.initializer) ||
    declaration.initializer.text !== runtime
  )
    throw new Error(
      "Saga toolkit is stale; run node scripts/build-saga-toolkit.mjs",
    );
} else fs.writeFileSync(target, output);
