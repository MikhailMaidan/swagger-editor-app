// Generate the portable checker at development time; the app never evaluates code.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const runtime =
  "const getByteSize = (text) => new TextEncoder().encode(text).length;\n" +
  ["consistency-model.ts", "consistency-engine.ts"]
    .map((name) =>
      ts
        .transpileModule(
          fs.readFileSync(path.join(root, "src/lib", name), "utf8"),
          {
            compilerOptions: {
              target: ts.ScriptTarget.ES2022,
              module: ts.ModuleKind.ESNext,
            },
          },
        )
        .outputText.replace(/^import[\s\S]*?;\s*/gm, ""),
    )
    .join("\n");
const target = path.join(root, "src/lib/consistency-runtime-source.ts");
if (process.argv.includes("--check")) {
  const old = ts.createSourceFile(
    target,
    fs.readFileSync(target, "utf8"),
    ts.ScriptTarget.Latest,
    true,
  );
  const declaration = old.statements
    .filter(ts.isVariableStatement)
    .flatMap((s) => s.declarationList.declarations)
    .find((d) => d.name.getText(old) === "CONSISTENCY_RUNTIME_SOURCE");
  if (
    !declaration?.initializer ||
    !ts.isStringLiteral(declaration.initializer) ||
    declaration.initializer.text !== runtime
  )
    throw new Error(
      "Consistency toolkit is stale; run node scripts/build-consistency-toolkit.mjs",
    );
} else
  fs.writeFileSync(
    target,
    "// Generated by node scripts/build-consistency-toolkit.mjs. Do not edit by hand.\nexport const CONSISTENCY_RUNTIME_SOURCE = " +
      JSON.stringify(runtime) +
      ";\n",
  );
