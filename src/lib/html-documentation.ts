function escapeHtml(value: unknown) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function renderText(value: string, fallback: string) {
  const text = value.trim() || fallback;
  return escapeHtml(text);
}

function getOperationKey(method: string, path: string) {
  return `${method.toUpperCase()} ${path}`;
}

function getRelatedModels(endpoints: EndpointSummary[], models: SchemaModel[]) {
  const operationKeys = new Set(
    endpoints.map((endpoint) =>
      getOperationKey(endpoint.method, endpoint.path),
    ),
  );
  const modelsByName = new Map(models.map((model) => [model.name, model]));
  const selectedNames = new Set<string>();
  const queue = models
    .filter((model) =>
      model.usages.some((usage) =>
        operationKeys.has(getOperationKey(usage.method, usage.path)),
      ),
    )
    .map((model) => model.name);

  while (queue.length > 0) {
    const name = queue.shift();

    if (!name || selectedNames.has(name)) continue;
    selectedNames.add(name);

    const model = modelsByName.get(name);
    model?.references.forEach((reference) => {
      if (modelsByName.has(reference) && !selectedNames.has(reference)) {
        queue.push(reference);
      }
    });
  }

  return models.filter((model) => selectedNames.has(model.name));
}

function getRelatedSecuritySchemes(
  endpoints: EndpointSummary[],
  securitySchemes: SecuritySchemeSummary[],
) {
  const names = new Set(
    endpoints.flatMap((endpoint) => endpoint.securityRequirements),
  );
  return securitySchemes.filter((scheme) => names.has(scheme.name));
}

function getParameterLocationLabel(
  location: EndpointParameter["location"],
  labels: DocumentationLabels,
) {
  return {
    cookie: labels.cookie,
    header: labels.header,
    path: labels.path,
    query: labels.query,
  }[location];
}

function getParameterConstraints(parameter: EndpointParameter) {
  const constraints = [
    parameter.enumValues?.length
      ? `enum: ${parameter.enumValues.join(", ")}`
      : "",
    parameter.minimum !== undefined ? `min: ${parameter.minimum}` : "",
    parameter.maximum !== undefined ? `max: ${parameter.maximum}` : "",
    parameter.minLength !== undefined
      ? `minLength: ${parameter.minLength}`
      : "",
    parameter.maxLength !== undefined
      ? `maxLength: ${parameter.maxLength}`
      : "",
    parameter.pattern ? `pattern: ${parameter.pattern}` : "",
  ].filter(Boolean);

  return constraints.join("; ");
}

function renderExample(example: string, labels: DocumentationLabels) {
  if (!example.trim()) return "";

  return `<div class="example"><p class="detail-label">${escapeHtml(labels.example)}</p><pre><code>${escapeHtml(example)}</code></pre></div>`;
}

function renderSchemaSummary(
  schema: SchemaDetails,
  labels: DocumentationLabels,
  includeExamples: boolean,
) {
  const properties = schema.properties.length
    ? `<p class="schema-properties"><strong>${escapeHtml(labels.properties)}:</strong> ${escapeHtml(schema.properties.join(", "))}</p>`
    : "";
  const example = includeExamples ? renderExample(schema.example, labels) : "";

  return `<div class="schema-summary">
    <p><strong>${escapeHtml(labels.schema)}:</strong> <code>${escapeHtml(schema.type || "unknown")}</code></p>
    ${properties}
    ${example}
  </div>`;
}

function renderParameters(
  parameters: EndpointParameter[],
  labels: DocumentationLabels,
  includeExamples: boolean,
) {
  if (parameters.length === 0) return "";

  const rows = parameters
    .map((parameter) => {
      const constraints = getParameterConstraints(parameter);

      return `<tr>
        <td><code>${escapeHtml(parameter.name)}</code></td>
        <td>${escapeHtml(getParameterLocationLabel(parameter.location, labels))}</td>
        <td><code>${escapeHtml(parameter.type || "string")}</code></td>
        <td>${escapeHtml(parameter.required ? labels.required : labels.optional)}</td>
        <td>${renderText(parameter.description, labels.noDescription)}</td>
        ${includeExamples ? `<td><code>${escapeHtml(parameter.example)}</code></td>` : ""}
        <td>${escapeHtml(constraints || "-")}</td>
      </tr>`;
    })
    .join("");

  return `<section class="contract-block">
    <h4>${escapeHtml(labels.parameters)}</h4>
    <div class="table-wrap"><table>
      <thead><tr>
        <th>${escapeHtml(labels.name)}</th>
        <th>${escapeHtml(labels.in)}</th>
        <th>${escapeHtml(labels.type)}</th>
        <th>${escapeHtml(labels.status)}</th>
        <th>${escapeHtml(labels.description)}</th>
        ${includeExamples ? `<th>${escapeHtml(labels.example)}</th>` : ""}
        <th>${escapeHtml(labels.format)}</th>
      </tr></thead>
      <tbody>${rows}</tbody>
    </table></div>
  </section>`;
}

function renderRequestBody(
  body: RequestBodySummary,
  index: number,
  labels: DocumentationLabels,
  includeExamples: boolean,
) {
  return `<div class="contract-item">
    <div class="contract-heading">
      <code>${escapeHtml(body.contentType || `body-${index + 1}`)}</code>
      <span class="chip">${escapeHtml(body.required ? labels.required : labels.optional)}</span>
    </div>
    ${body.description ? `<p>${escapeHtml(body.description)}</p>` : ""}
    ${renderSchemaSummary(body.schema, labels, includeExamples)}
  </div>`;
}

function renderRequestBodies(
  bodies: RequestBodySummary[],
  labels: DocumentationLabels,
  includeExamples: boolean,
) {
  if (bodies.length === 0) return "";

  return `<section class="contract-block">
    <h4>${escapeHtml(labels.requestBody)}</h4>
    ${bodies
      .map((body, index) =>
        renderRequestBody(body, index, labels, includeExamples),
      )
      .join("")}
  </section>`;
}

function renderResponse(
  response: ResponseSummary,
  labels: DocumentationLabels,
  includeExamples: boolean,
) {
  const headers = response.headers?.length
    ? `<div class="response-headers">
        <p class="detail-label">${escapeHtml(labels.responseHeaders)}</p>
        <ul>${response.headers
          .map(
            (header) =>
              `<li><code>${escapeHtml(header.name)}</code>${header.description ? ` - ${escapeHtml(header.description)}` : ""}</li>`,
          )
          .join("")}</ul>
      </div>`
    : "";
  const contentTypes = response.contentTypes.length
    ? `<p><strong>${escapeHtml(labels.contentTypes)}:</strong> ${escapeHtml(response.contentTypes.join(", "))}</p>`
    : "";
  const schema = response.schema
    ? renderSchemaSummary(response.schema, labels, includeExamples)
    : "";

  return `<div class="contract-item response-item">
    <div class="contract-heading">
      <span class="status-code">${escapeHtml(response.status)}</span>
      <strong>${renderText(response.description, labels.noDescription)}</strong>
    </div>
    ${contentTypes}
    ${headers}
    ${schema}
  </div>`;
}

function renderResponses(
  responses: ResponseSummary[],
  labels: DocumentationLabels,
  includeExamples: boolean,
) {
  return `<section class="contract-block">
    <h4>${escapeHtml(labels.responses)}</h4>
    ${
      responses.length
        ? responses
            .map((response) =>
              renderResponse(response, labels, includeExamples),
            )
            .join("")
        : `<p class="muted">${escapeHtml(labels.noResponses)}</p>`
    }
  </section>`;
}

function renderSecurityRequirement(
  endpoint: EndpointSummary,
  labels: DocumentationLabels,
) {
  if (!endpoint.secured) {
    return `<span class="chip public">${escapeHtml(labels.publicAccess)}</span>`;
  }

  const groups = endpoint.securityRequirementGroups?.length
    ? endpoint.securityRequirementGroups
        .map((group) => group.join(" + "))
        .join(" / ")
    : endpoint.securityRequirements.join(", ");

  return `<span class="chip secured">${escapeHtml(labels.authentication)}: ${escapeHtml(groups)}</span>`;
}

function renderEndpoint(
  endpoint: EndpointSummary,
  index: number,
  labels: DocumentationLabels,
  includeExamples: boolean,
) {
  const id = `operation-${index + 1}`;
  const method = endpoint.method.toUpperCase();
  const heading =
    endpoint.summary || endpoint.operationId || `${method} ${endpoint.path}`;
  const searchText = [
    method,
    endpoint.path,
    endpoint.summary,
    endpoint.description,
    endpoint.operationId,
    ...endpoint.tags,
    ...endpoint.securityRequirements,
  ]
    .join(" ")
    .toLowerCase();
  const tags = endpoint.tags.length
    ? `<div class="chips"><span class="detail-label">${escapeHtml(labels.tags)}</span>${endpoint.tags
        .map((tag) => `<span class="chip">${escapeHtml(tag)}</span>`)
        .join("")}</div>`
    : "";

  return {
    article: `<article class="endpoint" data-endpoint data-method="${escapeHtml(method)}" data-search="${escapeHtml(searchText)}" id="${id}">
      <header class="endpoint-heading">
        <span class="method method-${escapeHtml(method.toLowerCase())}">${escapeHtml(method)}</span>
        <div class="endpoint-title">
          <h3>${escapeHtml(heading)}</h3>
          <code>${escapeHtml(endpoint.path)}</code>
        </div>
      </header>
      <div class="chips">
        ${renderSecurityRequirement(endpoint, labels)}
        ${endpoint.deprecated ? `<span class="chip deprecated">${escapeHtml(labels.deprecated)}</span>` : ""}
        ${endpoint.operationId ? `<span class="chip"><code>${escapeHtml(endpoint.operationId)}</code></span>` : ""}
      </div>
      ${tags}
      ${endpoint.description ? `<p class="endpoint-description">${escapeHtml(endpoint.description)}</p>` : ""}
      ${renderParameters(endpoint.parameters, labels, includeExamples)}
      ${renderRequestBodies(endpoint.requestBodies, labels, includeExamples)}
      ${renderResponses(endpoint.responses, labels, includeExamples)}
    </article>`,
    id,
    label: `${method} ${endpoint.path}`,
    method,
    searchText,
  };
}

function renderModelProperty(
  property: SchemaModelProperty,
  labels: DocumentationLabels,
) {
  const details = [
    property.format ? `${labels.format}: ${property.format}` : "",
    property.enumValues.length
      ? `${labels.enum}: ${property.enumValues.join(", ")}`
      : "",
    property.nullable ? "nullable" : "",
    property.readOnly ? "readOnly" : "",
    property.writeOnly ? "writeOnly" : "",
    property.deprecated ? labels.deprecated : "",
  ].filter(Boolean);

  return `<tr>
    <td><code>${escapeHtml(property.name)}</code></td>
    <td><code>${escapeHtml(property.type)}</code></td>
    <td>${escapeHtml(property.required ? labels.required : labels.optional)}</td>
    <td>${renderText(property.description, labels.noDescription)}</td>
    <td>${escapeHtml(details.join("; ") || "-")}</td>
  </tr>`;
}

function renderModel(
  model: SchemaModel,
  labels: DocumentationLabels,
  includeExamples: boolean,
) {
  const usage = model.usages.length
    ? `<p><strong>${escapeHtml(labels.usage)}:</strong> ${model.usages
        .map(
          (item) =>
            `<code>${escapeHtml(`${item.method.toUpperCase()} ${item.path}`)}</code>`,
        )
        .join(", ")}</p>`
    : "";
  const properties = model.properties.length
    ? `<div class="table-wrap"><table>
        <thead><tr>
          <th>${escapeHtml(labels.name)}</th>
          <th>${escapeHtml(labels.type)}</th>
          <th>${escapeHtml(labels.status)}</th>
          <th>${escapeHtml(labels.description)}</th>
          <th>${escapeHtml(labels.format)}</th>
        </tr></thead>
        <tbody>${model.properties
          .map((property) => renderModelProperty(property, labels))
          .join("")}</tbody>
      </table></div>`
    : "";

  return `<article class="model" id="model-${escapeHtml(model.name.toLowerCase().replace(/[^a-z0-9]+/g, "-"))}">
    <header class="model-heading">
      <h3>${escapeHtml(model.name)}</h3>
      <code>${escapeHtml(model.type)}</code>
      ${model.deprecated ? `<span class="chip deprecated">${escapeHtml(labels.deprecated)}</span>` : ""}
    </header>
    ${model.description ? `<p>${escapeHtml(model.description)}</p>` : ""}
    ${usage}
    ${properties}
    <div class="example"><p class="detail-label">TypeScript</p><pre><code>${escapeHtml(model.typeScript)}</code></pre></div>
    ${includeExamples ? renderExample(model.example, labels) : ""}
  </article>`;
}

function renderSecurityScheme(scheme: SecuritySchemeSummary) {
  const details = [
    scheme.scheme,
    scheme.bearerFormat,
    scheme.parameterName,
    scheme.location,
  ].filter(Boolean);

  return `<article class="security-scheme">
    <div><h3>${escapeHtml(scheme.name)}</h3><code>${escapeHtml(scheme.type)}</code></div>
    ${details.length ? `<p>${escapeHtml(details.join(" · "))}</p>` : ""}
    ${scheme.description ? `<p>${escapeHtml(scheme.description)}</p>` : ""}
  </article>`;
}

