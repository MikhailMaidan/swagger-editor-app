export function createHtmlDocumentation(
  endpoints: EndpointSummary[],
  models: SchemaModel[],
  securitySchemes: SecuritySchemeSummary[],
  schema: { serverUrl: string; title: string; version: string },
  options: HtmlDocumentationOptions = {},
): HtmlDocumentationBuild {
  const includeDeprecated = options.includeDeprecated ?? true;
  const includeExamples = options.includeExamples ?? true;
  const includeModels = options.includeModels ?? true;
  const language = options.language ?? "en";
  const selectedEndpoints = includeDeprecated
    ? endpoints
    : endpoints.filter((endpoint) => !endpoint.deprecated);
  const selectedModels = includeModels
    ? getRelatedModels(selectedEndpoints, models)
    : [];
  const selectedSecuritySchemes = getRelatedSecuritySchemes(
    selectedEndpoints,
    securitySchemes,
  );

  return {
    html: renderDocument({
      endpoints: selectedEndpoints,
      includeExamples,
      labels: labelsByLanguage[language],
      language,
      models: selectedModels,
      schema,
      securitySchemes: selectedSecuritySchemes,
    }),
    summary: {
      deprecatedExcludedCount: includeDeprecated
        ? 0
        : endpoints.length - selectedEndpoints.length,
      endpointCount: selectedEndpoints.length,
      methodCount: new Set(
        selectedEndpoints.map((endpoint) => endpoint.method.toUpperCase()),
      ).size,
      modelCount: selectedModels.length,
      securitySchemeCount: selectedSecuritySchemes.length,
    },
  };
}
