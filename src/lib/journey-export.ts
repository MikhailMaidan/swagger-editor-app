import { compileJourneyModel } from "./journey-engine";
import { normalizeJourneyModel, type JourneyModel } from "./journey-project";
export function journeyGraphLayout(value: JourneyModel) {
  const model = normalizeJourneyModel(value),
    states = model.states.map((s, i) => ({
      ...s,
      x: 30 + (i % 4) * 190,
      y: 40 + Math.floor(i / 4) * 140,
    })),
    byId = new Map(states.map((s) => [s.id, s]));
  const edges = model.transitions.flatMap((t) => {
    const a = byId.get(t.from),
      b = byId.get(t.to);
    if (!a || !b) return [];
    const sx = a.x + 70,
      sy = a.y + 64,
      tx = b.x + 70,
      ty = b.y;
    return [
      {
        ...t,
        path:
          a.id === b.id
            ? `M ${a.x + 140} ${a.y + 20} C ${a.x + 190} ${a.y - 20} ${a.x + 190} ${a.y + 84} ${a.x + 140} ${a.y + 44}`
            : `M ${sx} ${sy} C ${sx} ${sy + 40} ${tx} ${ty - 40} ${tx} ${ty}`,
        labelX: a.id === b.id ? a.x + 120 : (sx + tx) / 2,
        labelY: a.id === b.id ? a.y - 8 : (sy + ty) / 2,
        label: `${Array.from(t.action).slice(0, 18).join("")} · ${t.statuses.slice(0, 3).join("/")}${t.statuses.length > 3 ? "…" : ""}`,
      },
    ];
  });
  return {
    model,
    states,
    edges,
    width: 800,
    height: Math.max(220, Math.ceil(states.length / 4) * 140 + 80),
  };
}
function xml(value: string) {
  return Array.from(value)
    .map((ch) => {
      const n = ch.codePointAt(0)!;
      return n === 9 ||
        n === 10 ||
        n === 13 ||
        (n >= 32 && n <= 0xd7ff) ||
        (n >= 0xe000 && n <= 0xfffd) ||
        n >= 0x10000
        ? ch
        : "�";
    })
    .join("")
    .replace(
      /[&<>"']/g,
      (c) =>
        ({
          "&": "&amp;",
          "<": "&lt;",
          ">": "&gt;",
          '"': "&quot;",
          "'": "&apos;",
        })[c]!,
    );
}
export function generateJourneySvg(value: JourneyModel): string {
  const g = journeyGraphLayout(value);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${g.width} ${g.height}" role="img" aria-label="${xml(g.model.name)}"><title>${xml(g.model.name)}</title><desc>Saved sequential API journey. Double borders indicate states where a trace may finish. Dashed edges are disabled.</desc><defs><marker id="journey-arrow" markerWidth="8" markerHeight="8" refX="7" refY="4" orient="auto"><path d="M0 0 L8 4 L0 8 Z" fill="#64748b"/></marker></defs><rect width="100%" height="100%" fill="white"/>${g.edges.map((t) => `<g><title>${xml(`${t.name}: ${t.action} [${t.statuses.join(", ")}]`)}</title><path d="${t.path}" fill="none" stroke="#64748b" stroke-width="1.5"${t.enabled ? "" : ' stroke-dasharray="5 4"'} marker-end="url(#journey-arrow)"/><text x="${t.labelX}" y="${t.labelY}" text-anchor="middle" font-family="sans-serif" font-size="9" fill="#475569">${xml(t.label)}</text></g>`).join("")}${g.states.map((s) => `<g><title>${xml(s.name)} (${xml(s.id)})</title><rect x="${s.x}" y="${s.y}" width="140" height="64" rx="12" fill="${s.id === g.model.initial ? "#ecfdf5" : "#f8fafc"}" stroke="#7c3aed" stroke-width="2"/>${s.terminal ? `<rect x="${s.x + 5}" y="${s.y + 5}" width="130" height="54" rx="9" fill="none" stroke="#7c3aed"/>` : ""}<text x="${s.x + 70}" y="${s.y + 29}" text-anchor="middle" font-family="sans-serif" font-size="12" fill="#0f172a">${xml(Array.from(s.name).slice(0, 20).join(""))}</text><text x="${s.x + 70}" y="${s.y + 47}" text-anchor="middle" font-family="sans-serif" font-size="10" fill="#64748b">${xml(s.id)}</text></g>`).join("")}</svg>`;
}
// Literal standalone ESM avoids serialized compiler/minifier closures.
export function generateJourneyMonitor(value: JourneyModel): string {
  const c = compileJourneyModel(value),
    definition = {
      id: c.model.id,
      initial: c.model.initial,
      terminal: [...c.terminal],
      edges: [...c.outgoing].flatMap(([from, events]) =>
        [...events].map(([key, edge]) => [
          from,
          key,
          edge.to,
          edge.transitionId,
        ]),
      ),
    };
  const literal = JSON.stringify(definition, null, 2)
    .replace(/</g, "\\u003c")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
  return `// Generated by RSSwag API journey and state-machine studio.
// Create one monitor per sequential workflow. Observe completed HTTP events.
// This records conformance; it does not send requests or roll back side effects.
const definition=${literal};
const encoder=new TextEncoder();
export function createJourneyMonitor(){
  const outgoing=new Map(),terminal=new Set(definition.terminal),journal=[];let current=definition.initial,total=0,rejected=0;
  for(const [from,key,to,transitionId] of definition.edges){if(!outgoing.has(from))outgoing.set(from,new Map());outgoing.get(from).set(key,{to,transitionId});}
  return {
    observe(value){
      if(!value||typeof value!=="object"||Array.isArray(value)||typeof value.action!=="string"||!value.action.trim()||value.action.length>256||encoder.encode(value.action).length>256||!Number.isInteger(value.status)||value.status<100||value.status>599)throw new TypeError("A bounded action label and integer HTTP status are required");
      const event={action:value.action,status:value.status},from=current,edge=outgoing.get(current)?.get(JSON.stringify([event.action,event.status]));if(edge)current=edge.to;else rejected++;
      const result={index:total++,event,allowed:!!edge,from,to:current,transitionId:edge?.transitionId??null,canFinish:terminal.has(current),reason:edge?"matched":"no-transition"};journal.push(result);if(journal.length>200)journal.shift();return {...result,event:{...event}};
    },
    snapshot(){return {modelId:definition.id,state:current,canFinish:terminal.has(current),total,rejected,dropped:Math.max(0,total-journal.length),journal:journal.map(r=>({...r,event:{...r.event}}))};},
    reset(){current=definition.initial;total=0;rejected=0;journal.length=0;}
  };
}
`;
}
