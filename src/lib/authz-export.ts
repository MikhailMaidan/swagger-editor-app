import { normalizeAuthzPolicy, type AuthzPolicy } from "./authz-project";

// Emit literal ESM instead of serializing functions whose compiled bodies can
// depend on bundler helpers. Artifact tests compare every condition and demo.
export function generateAuthzGuard(value: AuthzPolicy): string {
  const literal = JSON.stringify(normalizeAuthzPolicy(value), null, 2)
    .replace(/</g, "\\u003c")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
  return `// Generated by RSSwag authorization policy studio. No dependencies.
// Authenticate and load trusted resource attributes before classification.
// classify(request, ...context) may be asynchronous and must return
// {action, subject: object|null, resource: object, context: object}.
// Actions are exact application labels; only a whole '*' selector is a wildcard.
const policy = ${literal};
const object = v => v !== null && typeof v === "object" && !Array.isArray(v) && (Object.getPrototypeOf(v) === Object.prototype || Object.getPrototypeOf(v) === null);
function input(value) {
  const encoder = new TextEncoder();
  if (!object(value) || typeof value.action !== "string" || !value.action.trim() || encoder.encode(value.action).length > 256) throw new TypeError("Invalid authorization input");
  let nodes=0;const active=new Set();
  function clone(v,depth=0){
    if(++nodes>10000||depth>24)throw new TypeError("Authorization input limit");
    if(v===null||typeof v==="boolean"||typeof v==="string"||typeof v==="number"&&Number.isFinite(v))return v;
    if(typeof v!=="object"||active.has(v))throw new TypeError("Invalid authorization JSON");
    active.add(v);let result;
    if(Array.isArray(v)){if(v.length>10000||Object.keys(v).length!==v.length)throw new TypeError("Invalid authorization array");for(let i=0;i<v.length;i++)if(!Object.hasOwn(v,String(i)))throw new TypeError("Invalid authorization array");result=v.map(x=>clone(x,depth+1));}
    else if(object(v))result=Object.fromEntries(Object.entries(v).map(([key,x])=>[key,clone(x,depth+1)]));
    else throw new TypeError("Invalid authorization JSON");
    active.delete(v);return result;
  }
  const data=clone({subject:value.subject,resource:value.resource,context:value.context});
  if(encoder.encode(JSON.stringify(data)).length>65536||!(data.subject===null||object(data.subject))||!object(data.resource)||!object(data.context))throw new TypeError("Invalid authorization attributes");
  return {action:value.action,...data};
}
function resolve(operand,q){
  if(operand.source==="literal")return {found:true,value:operand.value};
  let value=q[operand.source];if(operand.pointer==="")return {found:true,value};
  for(const encoded of operand.pointer.slice(1).split("/")){
    const key=encoded.replace(/~1/g,"/").replace(/~0/g,"~");
    if(value===null||typeof value!=="object"||!Object.hasOwn(value,key)||Array.isArray(value)&&!/^(0|[1-9][0-9]*)$/.test(key))return {found:false};
    value=value[key];
  }return {found:true,value};
}
function equal(a,b){
  if(a===b)return true;
  if(a===null||b===null||typeof a!=="object"||typeof b!=="object"||Array.isArray(a)!==Array.isArray(b))return false;
  const keys=Object.keys(a);return keys.length===Object.keys(b).length&&keys.every(key=>Object.hasOwn(b,key)&&equal(a[key],b[key]));
}
function check(c,q,index){
  const left=resolve(c.left,q),right=c.right?resolve(c.right,q):{found:false};
  const result=(passed,reason=passed?"matched":"different")=>({index,operator:c.operator,passed,reason});
  if(c.operator==="exists")return result(left.found);
  if(c.operator==="absent")return result(!left.found);
  if(!left.found||!right.found)return result(false,"missing");
  const a=left.value,b=right.value;
  switch(c.operator){
    case "equal":return result(equal(a,b));
    case "notEqual":return result(!equal(a,b));
    case "in":return Array.isArray(b)?result(b.some(x=>equal(a,x))):result(false,"type");
    case "contains":return Array.isArray(a)?result(a.some(x=>equal(x,b))):result(false,"type");
    case "startsWith":return typeof a==="string"&&typeof b==="string"?result(a.startsWith(b)):result(false,"type");
    default:if(typeof a!=="number"||typeof b!=="number")return result(false,"type");
      return result(c.operator==="greater"?a>b:c.operator==="greaterOrEqual"?a>=b:c.operator==="less"?a<b:a<=b);
  }
}
export function evaluateAuthorization(value){
  const q=input(value),matchedAllow=[],matchedDeny=[];
  const rules=policy.rules.map(r=>{
    const base={id:r.id,name:r.name,effect:r.effect};
    if(!r.enabled)return {...base,status:"disabled",checks:[]};
    if(!r.actions.includes("*")&&!r.actions.includes(q.action))return {...base,status:"action",checks:[]};
    const checks=r.conditions.map((c,i)=>check(c,q,i)),matches=r.mode==="all"?checks.every(c=>c.passed):checks.some(c=>c.passed);
    if(matches)(r.effect==="allow"?matchedAllow:matchedDeny).push(r.id);
    return {...base,status:matches?"matched":"conditions",checks};
  });
  return {effect:matchedDeny.length||!matchedAllow.length?"deny":"allow",reason:matchedDeny.length?"explicit-deny":matchedAllow.length?"explicit-allow":"default-deny",matchedAllow,matchedDeny,rules};
}
export function createAuthorizationGuard(options){
  const classify=options?.classify,handler=options?.handler;
  if(typeof classify!=="function"||typeof handler!=="function")throw new TypeError("classify and handler functions are required");
  const refuse=(request,status,error)=>{
    try{void request.body?.cancel().catch(()=>{});}catch{}
    return new Response(request.method==="HEAD"?null:JSON.stringify({error}),{status,headers:{"content-type":"application/json","cache-control":"no-store"}});
  };
  return async function authorized(request,...args){
    let decision;
    try{decision=evaluateAuthorization(await classify.call(this,request,...args));}
    catch{return refuse(request,503,"authorization_unavailable");}
    if(decision.effect!=="allow")return refuse(request,403,"forbidden");
    return handler.call(this,request,decision,...args);
  };
}
`;
}
