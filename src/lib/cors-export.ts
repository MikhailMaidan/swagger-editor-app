import {
  CorsError,
  normalizeCorsPolicy,
  type CorsPolicy,
} from "./cors-project";
import { corsPolicyFindings } from "./cors-protocol";

// A literal ESM template keeps exports independent of TS transforms and minifier closures.
export function generateCorsMiddleware(value: CorsPolicy): string {
  const p = normalizeCorsPolicy(value);
  if (corsPolicyFindings(p).some((f) => f.error)) throw new CorsError("export");
  const policy = {
    origins: p.origins,
    methods: p.methods,
    requestHeaders: p.requestHeaders,
    exposeHeaders: p.exposeHeaders,
    credentials: p.credentials,
    maxAge: p.maxAge,
  };
  return `// Generated by RSSwag CORS policy studio. No runtime dependencies.
// Use one wrapper per route group. CORS is not application authorization.
// export default withCors(async request => Response.json({ ok: true }));
const definition = ${JSON.stringify(policy, null, 2)
    .replace(/</g, "\\u003c")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029")};
for (const value of Object.values(definition)) if (Array.isArray(value)) Object.freeze(value);
export const corsPolicy = Object.freeze(definition);
const corsFields = ["access-control-allow-origin", "access-control-allow-credentials", "access-control-allow-methods", "access-control-allow-headers", "access-control-max-age", "access-control-expose-headers"];
function applyCors(headers, origin, preflight) {
  for (const field of corsFields) headers.delete(field);
  const vary = new Set((headers.get("vary") || "").split(",").map(v => v.trim().toLowerCase()).filter(Boolean));
  vary.add("origin");
  if (preflight) { vary.add("access-control-request-method"); vary.add("access-control-request-headers"); }
  headers.set("vary", vary.has("*") ? "*" : [...vary].join(", "));
  if (origin === null || !(corsPolicy.origins.includes("*") || corsPolicy.origins.includes(origin))) return headers;
  headers.set("access-control-allow-origin", corsPolicy.origins.includes("*") ? "*" : origin);
  if (corsPolicy.credentials) headers.set("access-control-allow-credentials", "true");
  if (preflight) {
    headers.set("access-control-allow-methods", corsPolicy.methods.join(", "));
    headers.set("access-control-allow-headers", corsPolicy.requestHeaders.join(", "));
    headers.set("access-control-max-age", String(corsPolicy.maxAge));
  } else if (corsPolicy.exposeHeaders.length) headers.set("access-control-expose-headers", corsPolicy.exposeHeaders.join(", "));
  return headers;
}
export function withCors(handler) {
  if (typeof handler !== "function") throw new TypeError("A Fetch request handler is required");
  return async function corsHandler(request, ...args) {
    const origin = request.headers.get("origin");
    const preflight = request.method === "OPTIONS" && origin !== null && request.headers.has("access-control-request-method");
    if (preflight) return new Response(null, { status: 204, headers: applyCors(new Headers(), origin, true) });
    const response = await handler.call(this, request, ...args);
    if (!(response instanceof Response)) throw new TypeError("The handler must return a Response");
    if (response.status < 200) return response;
    return new Response(response.body, { status: response.status, statusText: response.statusText, headers: applyCors(new Headers(response.headers), origin, false) });
  };
}
`;
}
