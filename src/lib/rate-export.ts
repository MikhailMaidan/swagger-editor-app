import {
  MAX_RATE_HISTORY,
  normalizeRatePolicy,
  type RatePolicy,
} from "./rate-project";

// Literal source keeps the export independent of compiler/minifier closures.
// Executable artifact parity tests cover every algorithm against rate-engine.ts.
export function generateRateMiddleware(value: RatePolicy): string {
  const policy = normalizeRatePolicy(value);
  const literal = JSON.stringify(policy, null, 2)
    .replace(/</g, "\\u003c")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
  return `// Generated by RSSwag rate-limit and quota studio. No dependencies.
// State is local to one limiter instance. Use a shared atomic store for multiple processes.
// identify(request, ...context) must synchronously return trusted {client, route, cost}.
// Routes are application labels/templates; no headers are trusted automatically.
const definition = ${literal};
const encoder = new TextEncoder();
const integer = (v, min, max) => Number.isSafeInteger(v) && v >= min && v <= max;
const text = (v, max) => typeof v === "string" && v.length <= max && encoder.encode(v).length <= max;
const method = v => text(v, 32) && /^[!#$%&'*+.^_\\x60|~0-9A-Z-]+$/.test(v);
export class RateLimitError extends Error { constructor(code) { super(code); this.code = code; this.name = "RateLimitError"; } }
const identity = v => {
  if (!v || !text(v.client,120) || !v.client.trim() || !text(v.route,256) || !v.route.trim() || !method(v.method) || !integer(v.cost,1,10000)) throw new RateLimitError("request");
  return { client:v.client, route:v.route, method:v.method, cost:v.cost };
};
const ceil = (a,b) => Number((a+b-BigInt(1))/b);
export function createRateLimiter() {
  const stores = new Map(definition.rules.map(r=>[r.id,new Map()])); let lastNow = -1;
  const keyFor = (r,q) => JSON.stringify(r.scope==="global"?[]:r.scope==="client"?[q.client]:r.scope==="route"?[q.method,q.route]:[q.client,q.method,q.route]);
  const fullAt = (r,e) => e.at + ceil(BigInt(r.limit)*BigInt(r.refillMs)-e.credit,BigInt(r.refillTokens));
  function sweep(r,now) {
    const store=stores.get(r.id);
    for(const [key,e] of store) {
      if(r.algorithm==="fixed") {if(e.at+r.windowMs<=now)store.delete(key);}
      else if(r.algorithm==="token") {if(fullAt(r,e)<=now)store.delete(key);}
      else {let removed=0;while(removed<e.events.length&&e.events[removed].at+r.windowMs<=now){e.used-=e.events[removed].cost;removed++;}if(removed)e.events.splice(0,removed);if(!e.events.length)store.delete(key);}
    }
  }
  function take(input,now) {
    const q=identity(input);
    if(!integer(now,0,4102531200000)||now<lastNow)throw new RateLimitError("clock");lastNow=now;
    for(const r of definition.rules)sweep(r,now);
    const previews=definition.rules.filter(r=>r.enabled&&(r.matchMethod==="*"||r.matchMethod===q.method)&&(!r.matchRoute||r.matchRoute===q.route)).map(r=>{
      const store=stores.get(r.id),key=keyFor(r,q),existing=store.get(key),unit=BigInt(r.refillMs),maximum=BigInt(r.limit)*unit;
      let e,remaining=r.limit,wait=0,reason="none";
      if(r.algorithm==="fixed"){
        e=existing?{...existing,events:[]}:{at:Math.floor(now/r.windowMs)*r.windowMs,used:0,credit:BigInt(0),events:[]};remaining=r.limit-e.used;
        if(q.cost>r.limit){reason="cost";wait=null;}else if(q.cost>remaining){reason="limit";wait=e.at+r.windowMs-now;}
      } else if(r.algorithm==="sliding"){
        e=existing?{...existing,events:existing.events.map(event=>({...event}))}:{at:now,used:0,credit:BigInt(0),events:[]};remaining=r.limit-e.used;
        if(q.cost>r.limit){reason="cost";wait=null;}else if(q.cost>remaining){reason="limit";let freed=0;for(const event of e.events){freed+=event.cost;if(e.used-freed+q.cost<=r.limit){wait=event.at+r.windowMs-now;break;}}}
        else if(e.events.length>=${MAX_RATE_HISTORY}&&e.events.at(-1)?.at!==now){reason="history-capacity";wait=e.events[0].at+r.windowMs-now;}
      } else {
        const credit=existing?existing.credit+BigInt(now-existing.at)*BigInt(r.refillTokens):maximum;
        e={at:now,credit:credit>maximum?maximum:credit,used:0,events:[]};remaining=Number(e.credit/unit);
        if(q.cost>r.limit){reason="cost";wait=null;}else if(e.credit<BigInt(q.cost)*unit){reason="limit";wait=ceil(BigInt(q.cost)*unit-e.credit,BigInt(r.refillTokens));}
      }
      if(reason==="none"&&!existing&&store.size>=r.keyCapacity){
        reason="key-capacity";let earliest=Infinity;
        for(const entry of store.values()){const expiry=r.algorithm==="fixed"?entry.at+r.windowMs:r.algorithm==="token"?fullAt(r,entry):entry.events.at(-1).at+r.windowMs;earliest=Math.min(earliest,expiry);}wait=earliest-now;
      }
      const decision={id:r.id,name:r.name,algorithm:r.algorithm,scope:r.scope,wouldAllow:reason==="none",charged:false,reason,remaining,retryAfterMs:reason==="none"?0:wait,keys:store.size,history:e.events.length};
      return {r,store,key,e,decision};
    });
    const denied=previews.filter(x=>!x.decision.wouldAllow),allowed=denied.length===0;
    if(allowed)for(const {r,store,key,e,decision} of previews){
      if(r.algorithm==="token")e.credit-=BigInt(q.cost)*BigInt(r.refillMs);
      else {e.used+=q.cost;if(r.algorithm==="sliding"){const last=e.events.at(-1);if(last?.at===now)last.cost+=q.cost;else e.events.push({at:now,cost:q.cost});}}
      store.set(key,e);decision.charged=true;decision.remaining=r.algorithm==="token"?Number(e.credit/BigInt(r.refillMs)):r.limit-e.used;decision.keys=store.size;decision.history=e.events.length;
    }
    const outcome=!previews.length?"unmatched":allowed?"allowed":denied.some(x=>x.decision.reason==="key-capacity"||x.decision.reason==="history-capacity")?"capacity":"limited";
    return {allowed,outcome,retryAfterMs:allowed?0:denied.some(x=>x.decision.retryAfterMs===null)?null:Math.max(...denied.map(x=>x.decision.retryAfterMs)),rules:previews.map(x=>x.decision)};
  }
  return {take,reset(){for(const store of stores.values())store.clear();lastNow=-1;}};
}
export function createRateLimitMiddleware(options) {
  const identify=options?.identify,handler=options?.handler,clock=options?.now??Date.now;
  if(typeof identify!=="function"||typeof handler!=="function"||typeof clock!=="function")throw new TypeError("Synchronous identify, handler and clock functions are required");
  const limiter=createRateLimiter();
  const refusal=(request,status,error,wait=null)=>{
    try{void request.body?.cancel().catch(()=>{});}catch{}
    const headers={"content-type":"application/json","cache-control":"no-store"};
    if(wait!==null)headers["retry-after"]=String(Math.ceil(wait/1000));
    return new Response(request.method==="HEAD"?null:JSON.stringify({error,retryAfterMs:wait}),{status,headers});
  };
  return async function rateLimited(request,...args){
    let q,now,decision;
    try {q=identify.call(this,request,...args);if(q&&typeof q.then==="function"){void Promise.resolve(q).catch(()=>{});throw new RateLimitError("request");}q=identity({...q,method:request.method});}
    catch{return refusal(request,400,"invalid_rate_limit_identity");}
    try{now=clock();decision=limiter.take(q,now);}catch(error){return refusal(request,503,error.code==="clock"?"rate_limit_clock":"rate_limit_unavailable");}
    if(!decision.allowed)return refusal(request,decision.outcome==="capacity"?503:429,decision.outcome==="capacity"?"rate_limit_capacity":"rate_limited",decision.retryAfterMs);
    return handler.call(this,request,decision,...args);
  };
}
`;
}
